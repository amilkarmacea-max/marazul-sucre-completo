SET NAMES utf8mb4;
DROP DATABASE IF EXISTS marazul_sucre;
CREATE DATABASE marazul_sucre CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE marazul_sucre;

CREATE TABLE countries (
    country_id INT AUTO_INCREMENT,
    iso_code CHAR(2) NOT NULL,
    name VARCHAR(60) NOT NULL,
    CONSTRAINT pk_countries PRIMARY KEY (country_id),
    CONSTRAINT uq_countries_iso_code UNIQUE (iso_code),
    CONSTRAINT uq_countries_name UNIQUE (name)
) ENGINE = InnoDB;

CREATE TABLE departments (
    department_id INT AUTO_INCREMENT,
    dane_code CHAR(2) NOT NULL,
    name VARCHAR(60) NOT NULL,
    country_id INT NOT NULL,
    CONSTRAINT pk_departments PRIMARY KEY (department_id),
    CONSTRAINT uq_departments_dane_code UNIQUE (dane_code),
    CONSTRAINT fk_departments_countries FOREIGN KEY (country_id) REFERENCES countries (country_id)
) ENGINE = InnoDB;

CREATE TABLE municipalities (
    municipality_id INT AUTO_INCREMENT,
    dane_code CHAR(5) NOT NULL,
    name VARCHAR(60) NOT NULL,
    subregion VARCHAR(30) NOT NULL,
    department_id INT NOT NULL,
    CONSTRAINT pk_municipalities PRIMARY KEY (municipality_id),
    CONSTRAINT uq_municipalities_dane_code UNIQUE (dane_code),
    CONSTRAINT fk_municipalities_departments FOREIGN KEY (department_id) REFERENCES departments (department_id)
) ENGINE = InnoDB;

CREATE TABLE maritime_areas (
    area_id INT AUTO_INCREMENT,
    name VARCHAR(80) NOT NULL,
    country_id INT NOT NULL,
    CONSTRAINT pk_maritime_areas PRIMARY KEY (area_id),
    CONSTRAINT uq_maritime_areas_name UNIQUE (name),
    CONSTRAINT fk_maritime_areas_countries FOREIGN KEY (country_id) REFERENCES countries (country_id)
) ENGINE = InnoDB;

CREATE TABLE fishing_zones (
    zone_id INT AUTO_INCREMENT,
    name VARCHAR(80) NOT NULL,
    zone_type VARCHAR(20) NOT NULL,
    latitude DECIMAL(9,6) NOT NULL,
    longitude DECIMAL(9,6) NOT NULL,
    area_id INT NOT NULL,
    CONSTRAINT pk_fishing_zones PRIMARY KEY (zone_id),
    CONSTRAINT uq_fishing_zones_name UNIQUE (name),
    CONSTRAINT ck_fishing_zones_zone_type CHECK (zone_type IN ('MAR_ABIERTO', 'GOLFO', 'MANGLAR', 'CIENAGA', 'RIO', 'ESTANQUE')),
    CONSTRAINT ck_fishing_zones_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_fishing_zones_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT fk_fishing_zones_maritime_areas FOREIGN KEY (area_id) REFERENCES maritime_areas (area_id)
) ENGINE = InnoDB;

CREATE TABLE organizations (
    organization_id INT AUTO_INCREMENT,
    tax_id VARCHAR(15) NOT NULL,
    name VARCHAR(120) NOT NULL,
    organization_type VARCHAR(25) NOT NULL,
    phone VARCHAR(15) NULL,
    municipality_id INT NOT NULL,
    CONSTRAINT pk_organizations PRIMARY KEY (organization_id),
    CONSTRAINT uq_organizations_tax_id UNIQUE (tax_id),
    CONSTRAINT ck_organizations_type CHECK (organization_type IN ('ASOCIACION', 'COOPERATIVA', 'COMERCIALIZADORA')),
    CONSTRAINT fk_organizations_municipalities FOREIGN KEY (municipality_id) REFERENCES municipalities (municipality_id)
) ENGINE = InnoDB;

CREATE TABLE fishermen (
    fisherman_id INT AUTO_INCREMENT,
    document_number VARCHAR(15) NOT NULL,
    first_names VARCHAR(60) NOT NULL,
    last_names VARCHAR(60) NOT NULL,
    birth_date DATE NOT NULL,
    aunap_card VARCHAR(20) NULL,
    phone VARCHAR(15) NULL,
    organization_id INT NOT NULL,
    CONSTRAINT pk_fishermen PRIMARY KEY (fisherman_id),
    CONSTRAINT uq_fishermen_document_number UNIQUE (document_number),
    CONSTRAINT uq_fishermen_aunap_card UNIQUE (aunap_card),
    CONSTRAINT fk_fishermen_organizations FOREIGN KEY (organization_id) REFERENCES organizations (organization_id)
) ENGINE = InnoDB;

CREATE TABLE vessels (
    vessel_id INT AUTO_INCREMENT,
    registration_number VARCHAR(20) NOT NULL,
    name VARCHAR(60) NOT NULL,
    vessel_type VARCHAR(20) NOT NULL,
    length_m DECIMAL(5,2) NOT NULL,
    load_capacity_kg DECIMAL(8,2) NOT NULL,
    organization_id INT NOT NULL,
    CONSTRAINT pk_vessels PRIMARY KEY (vessel_id),
    CONSTRAINT uq_vessels_registration_number UNIQUE (registration_number),
    CONSTRAINT ck_vessels_type CHECK (vessel_type IN ('CANOA', 'CHALUPA', 'BOTE', 'LANCHA')),
    CONSTRAINT ck_vessels_length CHECK (length_m > 0),
    CONSTRAINT ck_vessels_load_capacity CHECK (load_capacity_kg > 0),
    CONSTRAINT fk_vessels_organizations FOREIGN KEY (organization_id) REFERENCES organizations (organization_id)
) ENGINE = InnoDB;

CREATE TABLE employees (
    employee_id INT AUTO_INCREMENT,
    document_number VARCHAR(15) NOT NULL,
    first_names VARCHAR(60) NOT NULL,
    last_names VARCHAR(60) NOT NULL,
    position VARCHAR(30) NOT NULL,
    email VARCHAR(100) NOT NULL,
    CONSTRAINT pk_employees PRIMARY KEY (employee_id),
    CONSTRAINT uq_employees_document_number UNIQUE (document_number),
    CONSTRAINT uq_employees_email UNIQUE (email),
    CONSTRAINT ck_employees_position CHECK (position IN ('COORDINADOR_JORNADA', 'INSPECTOR_CALIDAD', 'RESPONSABLE_COMERCIAL', 'ADMINISTRADOR'))
) ENGINE = InnoDB;

CREATE TABLE roles (
    role_id INT AUTO_INCREMENT,
    role_name VARCHAR(40) NOT NULL,
    description VARCHAR(150) NOT NULL,
    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uq_roles_role_name UNIQUE (role_name)
) ENGINE = InnoDB;

CREATE TABLE users (
    user_id INT AUTO_INCREMENT,
    username VARCHAR(32) NOT NULL,
    role_id INT NOT NULL,
    employee_id INT NULL,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_employee_id UNIQUE (employee_id),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT fk_users_roles FOREIGN KEY (role_id) REFERENCES roles (role_id),
    CONSTRAINT fk_users_employees FOREIGN KEY (employee_id) REFERENCES employees (employee_id)
) ENGINE = InnoDB;

CREATE TABLE fishing_gears (
    gear_id INT AUTO_INCREMENT,
    name VARCHAR(50) NOT NULL,
    gear_type VARCHAR(20) NOT NULL,
    selectivity VARCHAR(10) NOT NULL,
    CONSTRAINT pk_fishing_gears PRIMARY KEY (gear_id),
    CONSTRAINT uq_fishing_gears_name UNIQUE (name),
    CONSTRAINT ck_fishing_gears_type CHECK (gear_type IN ('RED', 'ANZUELO', 'TRAMPA', 'ARPON')),
    CONSTRAINT ck_fishing_gears_selectivity CHECK (selectivity IN ('ALTA', 'MEDIA', 'BAJA'))
) ENGINE = InnoDB;

CREATE TABLE fishing_trips (
    trip_id INT AUTO_INCREMENT,
    vessel_id INT NOT NULL,
    zone_id INT NOT NULL,
    coordinator_id INT NOT NULL,
    departure_at DATETIME NOT NULL,
    return_at DATETIME NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PROGRAMADA',
    CONSTRAINT pk_fishing_trips PRIMARY KEY (trip_id),
    CONSTRAINT ck_fishing_trips_status CHECK (status IN ('PROGRAMADA', 'EN_CURSO', 'FINALIZADA', 'CANCELADA')),
    CONSTRAINT ck_fishing_trips_dates CHECK (return_at IS NULL OR return_at > departure_at),
    CONSTRAINT fk_fishing_trips_vessels FOREIGN KEY (vessel_id) REFERENCES vessels (vessel_id),
    CONSTRAINT fk_fishing_trips_fishing_zones FOREIGN KEY (zone_id) REFERENCES fishing_zones (zone_id),
    CONSTRAINT fk_fishing_trips_employees FOREIGN KEY (coordinator_id) REFERENCES employees (employee_id),
    INDEX idx_fishing_trips_departure_at (departure_at)
) ENGINE = InnoDB;

CREATE TABLE trip_crew (
    trip_id INT NOT NULL,
    fisherman_id INT NOT NULL,
    crew_role VARCHAR(25) NOT NULL DEFAULT 'TRIPULANTE',
    CONSTRAINT pk_trip_crew PRIMARY KEY (trip_id, fisherman_id),
    CONSTRAINT ck_trip_crew_role CHECK (crew_role IN ('RESPONSABLE', 'TRIPULANTE')),
    CONSTRAINT fk_trip_crew_fishing_trips FOREIGN KEY (trip_id) REFERENCES fishing_trips (trip_id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_crew_fishermen FOREIGN KEY (fisherman_id) REFERENCES fishermen (fisherman_id),
    UNIQUE INDEX uq_trip_crew_one_responsible ((CASE WHEN crew_role = 'RESPONSABLE' THEN trip_id END))
) ENGINE = InnoDB;

CREATE TABLE trip_gears (
    trip_id INT NOT NULL,
    gear_id INT NOT NULL,
    CONSTRAINT pk_trip_gears PRIMARY KEY (trip_id, gear_id),
    CONSTRAINT fk_trip_gears_fishing_trips FOREIGN KEY (trip_id) REFERENCES fishing_trips (trip_id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_gears_fishing_gears FOREIGN KEY (gear_id) REFERENCES fishing_gears (gear_id)
) ENGINE = InnoDB;

CREATE TABLE species (
    species_id INT AUTO_INCREMENT,
    common_name VARCHAR(60) NOT NULL,
    scientific_name VARCHAR(80) NOT NULL,
    min_size_cm DECIMAL(5,1) NOT NULL,
    habitat_type VARCHAR(20) NOT NULL,
    organoleptic_description TEXT NOT NULL,
    CONSTRAINT pk_species PRIMARY KEY (species_id),
    CONSTRAINT uq_species_common_name UNIQUE (common_name),
    CONSTRAINT uq_species_scientific_name UNIQUE (scientific_name),
    CONSTRAINT ck_species_min_size CHECK (min_size_cm > 0),
    CONSTRAINT ck_species_habitat CHECK (habitat_type IN ('MARINO', 'ESTUARINO', 'DULCEACUICOLA'))
) ENGINE = InnoDB;

CREATE TABLE species_local_names (
    species_id INT NOT NULL,
    local_name VARCHAR(60) NOT NULL,
    CONSTRAINT pk_species_local_names PRIMARY KEY (species_id, local_name),
    CONSTRAINT fk_species_local_names_species FOREIGN KEY (species_id) REFERENCES species (species_id) ON DELETE CASCADE
) ENGINE = InnoDB;

CREATE TABLE collection_centers (
    center_id INT AUTO_INCREMENT,
    name VARCHAR(80) NOT NULL,
    capacity_kg DECIMAL(9,2) NOT NULL,
    refrigerated BOOLEAN NOT NULL DEFAULT TRUE,
    municipality_id INT NOT NULL,
    CONSTRAINT pk_collection_centers PRIMARY KEY (center_id),
    CONSTRAINT uq_collection_centers_name UNIQUE (name),
    CONSTRAINT ck_collection_centers_capacity CHECK (capacity_kg > 0),
    CONSTRAINT fk_collection_centers_municipalities FOREIGN KEY (municipality_id) REFERENCES municipalities (municipality_id)
) ENGINE = InnoDB;

CREATE TABLE catches (
    catch_id INT AUTO_INCREMENT,
    species_id INT NOT NULL,
    trip_id INT NOT NULL,
    center_id INT NULL,
    weight_kg DECIMAL(8,2) NOT NULL,
    piece_count INT NOT NULL,
    avg_size_cm DECIMAL(5,1) NULL,
    available_weight_kg DECIMAL(8,2) NOT NULL DEFAULT 0,
    landed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_catches PRIMARY KEY (catch_id),
    CONSTRAINT ck_catches_weight CHECK (weight_kg > 0),
    CONSTRAINT ck_catches_piece_count CHECK (piece_count > 0),
    CONSTRAINT ck_catches_avg_size CHECK (avg_size_cm IS NULL OR avg_size_cm > 0),
    CONSTRAINT ck_catches_available CHECK (available_weight_kg >= 0 AND available_weight_kg <= weight_kg),
    CONSTRAINT fk_catches_species FOREIGN KEY (species_id) REFERENCES species (species_id),
    CONSTRAINT fk_catches_fishing_trips FOREIGN KEY (trip_id) REFERENCES fishing_trips (trip_id),
    CONSTRAINT fk_catches_collection_centers FOREIGN KEY (center_id) REFERENCES collection_centers (center_id),
    INDEX idx_catches_landed_at (landed_at)
) ENGINE = InnoDB;

CREATE TABLE buyers (
    buyer_id INT AUTO_INCREMENT,
    document_number VARCHAR(15) NOT NULL,
    name VARCHAR(120) NOT NULL,
    buyer_type VARCHAR(20) NOT NULL,
    phone VARCHAR(15) NULL,
    municipality_id INT NOT NULL,
    CONSTRAINT pk_buyers PRIMARY KEY (buyer_id),
    CONSTRAINT uq_buyers_document_number UNIQUE (document_number),
    CONSTRAINT ck_buyers_type CHECK (buyer_type IN ('RESTAURANTE', 'PESCADERIA', 'HOTEL', 'MAYORISTA', 'PARTICULAR')),
    CONSTRAINT fk_buyers_municipalities FOREIGN KEY (municipality_id) REFERENCES municipalities (municipality_id)
) ENGINE = InnoDB;

CREATE TABLE sales (
    sale_id INT AUTO_INCREMENT,
    buyer_id INT NOT NULL,
    employee_id INT NOT NULL,
    sale_date DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(10) NOT NULL DEFAULT 'REGISTRADA',
    CONSTRAINT pk_sales PRIMARY KEY (sale_id),
    CONSTRAINT ck_sales_status CHECK (status IN ('REGISTRADA', 'PAGADA', 'ANULADA')),
    CONSTRAINT fk_sales_buyers FOREIGN KEY (buyer_id) REFERENCES buyers (buyer_id),
    CONSTRAINT fk_sales_employees FOREIGN KEY (employee_id) REFERENCES employees (employee_id)
) ENGINE = InnoDB;

CREATE TABLE sale_details (
    detail_id INT AUTO_INCREMENT,
    sale_id INT NOT NULL,
    catch_id INT NOT NULL,
    sold_weight_kg DECIMAL(8,2) NOT NULL,
    unit_price DECIMAL(10,2) NOT NULL,
    subtotal DECIMAL(12,2) GENERATED ALWAYS AS (sold_weight_kg * unit_price) STORED,
    CONSTRAINT pk_sale_details PRIMARY KEY (detail_id),
    CONSTRAINT ck_sale_details_sold_weight CHECK (sold_weight_kg > 0),
    CONSTRAINT ck_sale_details_unit_price CHECK (unit_price > 0),
    CONSTRAINT fk_sale_details_sales FOREIGN KEY (sale_id) REFERENCES sales (sale_id),
    CONSTRAINT fk_sale_details_catches FOREIGN KEY (catch_id) REFERENCES catches (catch_id)
) ENGINE = InnoDB;

CREATE TABLE catch_audit (
    audit_id INT AUTO_INCREMENT,
    changed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    db_user VARCHAR(288) NOT NULL,
    catch_id INT NOT NULL,
    old_weight DECIMAL(8,2) NULL,
    new_weight DECIMAL(8,2) NULL,
    old_available DECIMAL(8,2) NULL,
    new_available DECIMAL(8,2) NULL,
    CONSTRAINT pk_catch_audit PRIMARY KEY (audit_id),
    INDEX idx_catch_audit_catch_id (catch_id)
) ENGINE = InnoDB;

